"""Content guardrails.

Two tiers, both plain code (no LLM judgment involved):

Tier A -- deterministic cleanup, always applied silently to every string
field before rendering (emoji removal, dash normalization).

Tier B -- validation that returns a list of human-readable violations.
`pipeline.py` feeds these back into the planner as a correction request
and retries a bounded number of times; if violations remain after
retries are exhausted, generation fails loudly instead of shipping a
deck that violates the user's design rules.

Limitation (documented, not hidden): this is substring/regex matching,
not semantic understanding. A correctly-derived number (e.g. a percentage
computed from two raw figures) can false-positive as "untraceable," and
it cannot catch every possible phrasing of filler content. It catches the
common failure modes -- invented round stats, boilerplate AI phrasing,
self-referential AI branding -- not every possible one.
"""

from __future__ import annotations

import re

from src.schema import SlidePlan

_EMOJI_RE = re.compile(
    "["
    "\U0001F300-\U0001FAFF"
    "\U00002600-\U000026FF"
    "\U00002700-\U000027BF"
    "\U0001F1E6-\U0001F1FF"
    "\U00002B00-\U00002BFF"
    "️"
    "]+",
    flags=re.UNICODE,
)

_NUMERIC_DASH_RE = re.compile(r"(?<=\d)\s*[‒–—]\s*(?=\d)")
_DASH_RE = re.compile(r"\s*[‒–—]\s*")

_NUMBER_RE = re.compile(r"\d[\d,.]*%?")

FILLER_PHRASES = [
    "unlock the power of",
    "revolutionize",
    "revolutionary",
    "seamless synergy",
    "synergy",
    "cutting-edge",
    "cutting edge",
    "state-of-the-art",
    "state of the art",
    "game-changer",
    "game changer",
    "paradigm shift",
    "empower",
    "unleash",
    "supercharge",
    "take it to the next level",
    "in today's fast-paced world",
    "disrupt",
    "disruptive",
    "next-generation",
    "next generation",
    "world-class",
    "best-in-class",
    "one-stop shop",
    "think outside the box",
]

BRANDING_PHRASES = [
    "made with ai",
    "made using ai",
    "ai-generated",
    "ai generated",
    "generated by ai",
    "powered by ai",
    "made with gemini",
    "made with claude",
    "created with ai",
    "built with ai",
]


def strip_emoji(text: str) -> str:
    return _EMOJI_RE.sub("", text).strip()


def normalize_dashes(text: str) -> str:
    # Numeric ranges (e.g. "2020-2024") collapse to a plain hyphen with no
    # surrounding spaces; everything else becomes a comma clause.
    text = _NUMERIC_DASH_RE.sub("-", text)
    text = _DASH_RE.sub(", ", text)
    return text


def _clean_text(text: str) -> str:
    return normalize_dashes(strip_emoji(text))


def _clean_value(value):
    if isinstance(value, str):
        return _clean_text(value)
    if isinstance(value, list):
        return [_clean_value(v) for v in value]
    if isinstance(value, dict):
        return {k: _clean_value(v) for k, v in value.items()}
    return value


def sanitize_plan(plan: SlidePlan) -> SlidePlan:
    """Apply Tier A cleanup to every string field in the plan."""
    cleaned = _clean_value(plan.model_dump())
    return SlidePlan(**cleaned)


def find_filler_phrases(text: str) -> list[str]:
    lower = text.lower()
    return [phrase for phrase in FILLER_PHRASES if phrase in lower]


def find_branding(text: str) -> list[str]:
    lower = text.lower()
    return [phrase for phrase in BRANDING_PHRASES if phrase in lower]


def _slide_texts(slide) -> list[str]:
    texts: list[str] = []
    for field in ("title", "subtitle", "left_heading", "right_heading", "quote_text", "quote_attribution", "stat_label"):
        value = getattr(slide, field, None)
        if value:
            texts.append(value)
    for field in ("body", "left_items", "right_items", "table_headers"):
        value = getattr(slide, field, None)
        if value:
            texts.extend(value)
    if slide.table_rows:
        for row in slide.table_rows:
            texts.extend(row)
    return texts


def check_stat_traceability(plan: SlidePlan, raw_data: str) -> list[str]:
    normalized_raw = re.sub(r"[,\s]", "", raw_data)
    violations: list[str] = []

    for i, slide in enumerate(plan.slides):
        candidates = []
        if slide.stat_value:
            candidates.append(slide.stat_value)
        if slide.body:
            candidates.extend(slide.body)

        for text in candidates:
            for number in _NUMBER_RE.findall(text):
                normalized_number = re.sub(r"[,\s%]", "", number)
                if normalized_number and normalized_number not in normalized_raw:
                    violations.append(
                        f"slide {i} ({slide.layout.value}) contains number "
                        f"{number!r} that does not appear in the supplied raw data"
                    )
    return violations


def validate_plan(plan: SlidePlan, raw_data: str) -> list[str]:
    """Run all Tier B checks, returning every violation found."""
    violations: list[str] = []

    for i, slide in enumerate(plan.slides):
        for text in _slide_texts(slide):
            for phrase in find_filler_phrases(text):
                violations.append(f"slide {i} ({slide.layout.value}) uses filler phrase {phrase!r}")
            for phrase in find_branding(text):
                violations.append(f"slide {i} ({slide.layout.value}) contains AI-branding phrase {phrase!r}")

    violations.extend(check_stat_traceability(plan, raw_data))
    return violations
